/*
  Taller 1 - Caso C - 02_carga.sql

  Llenamos la estrella a partir de lo que cargamos en el Lab 4 (CURSO.LAB4). Primero van las
  dimensiones, porque ahí se crean las llaves, y al final el hecho, que las usa.
  Usamos INSERT OVERWRITE, que borra y vuelve a llenar, así que se puede correr cuantas veces
  se quiera y siempre queda igual.

  En DIM_ZONA agrupamos por nombre para que Corona y Governor's Island queden una sola vez.
  Si uníamos sin hacer esto, el hecho quedaba con 46911 filas y 60452731 viajes (sobraban 196
  filas y 184265 viajes).

  Al final está el conteo de control. Nos dio 46715 filas y 60268466 viajes, igual que el paquete.
  Se corre con Run All.
*/

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE SCHEMA CURSO.T1;

INSERT OVERWRITE INTO DIM_EMPRESA (EMPRESA_KEY, EMPRESA)
SELECT ROW_NUMBER() OVER (ORDER BY EMPRESA), EMPRESA
FROM (SELECT DISTINCT EMPRESA FROM CURSO.LAB4.DAILY_ZONE_METRICS);

INSERT OVERWRITE INTO DIM_ZONA (ZONA_KEY, ZONA, BOROUGH, SERVICE_ZONE, LOCATION_ID)
SELECT ROW_NUMBER() OVER (ORDER BY ZONA), ZONA, BOROUGH, SERVICE_ZONE, LOCATION_ID
FROM (
  SELECT ZONA, MIN(BOROUGH) AS BOROUGH, MIN(SERVICE_ZONE) AS SERVICE_ZONE, MIN(LOCATION_ID) AS LOCATION_ID
  FROM CURSO.LAB4.DIM_ZONA
  GROUP BY ZONA
);

INSERT OVERWRITE INTO DIM_FECHA (FECHA, ANIO, MES_NUM, MES)
SELECT FECHA, YEAR(FECHA), MONTH(FECHA), TO_CHAR(FECHA, 'YYYY-MM')
FROM (SELECT DISTINCT FECHA FROM CURSO.LAB4.DAILY_ZONE_METRICS);

INSERT OVERWRITE INTO FACT_VIAJES_DIA
  (FECHA, ZONA_KEY, EMPRESA_KEY, VIAJES, INGRESO_TOTAL, PROPINA_TOTAL, DISTANCIA_TOTAL)
SELECT G.FECHA, Z.ZONA_KEY, E.EMPRESA_KEY, G.VIAJES, G.INGRESO_TOTAL,
       G.PROPINA_PROMEDIO * G.VIAJES,
       G.DISTANCIA_PROMEDIO * G.VIAJES
FROM CURSO.LAB4.DAILY_ZONE_METRICS G
LEFT JOIN DIM_ZONA Z    ON Z.ZONA = G.ZONA
LEFT JOIN DIM_EMPRESA E ON E.EMPRESA = G.EMPRESA;

SELECT 'FACT_VIAJES_DIA' AS TABLA, COUNT(*) AS FILAS, SUM(VIAJES) AS VIAJES FROM FACT_VIAJES_DIA
UNION ALL SELECT 'DIM_FECHA',   COUNT(*), NULL FROM DIM_FECHA
UNION ALL SELECT 'DIM_ZONA',    COUNT(*), NULL FROM DIM_ZONA
UNION ALL SELECT 'DIM_EMPRESA', COUNT(*), NULL FROM DIM_EMPRESA;
